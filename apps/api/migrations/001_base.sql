-- 001: esquema base, equivalente ao SQLite atual (permite importar os dados com os mesmos IDs).
CREATE TABLE teachers(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE, name text NOT NULL, password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE classes(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE, is_demo integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE students(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL, class_id integer REFERENCES classes(id),
  username text NOT NULL UNIQUE, pin_hash text NOT NULL, pin_fp text NOT NULL UNIQUE,
  active integer NOT NULL DEFAULT 1, is_demo integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX ix_students_class ON students(class_id);
CREATE TABLE maps(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sort integer NOT NULL UNIQUE, slug text NOT NULL UNIQUE, title text NOT NULL,
  subtitle text NOT NULL, topics jsonb NOT NULL, status text NOT NULL DEFAULT 'developing');
CREATE TABLE questions(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  map_id integer NOT NULL REFERENCES maps(id), number integer NOT NULL,
  title text NOT NULL, theme text NOT NULL, scene text NOT NULL, scenario text NOT NULL, dialog text NOT NULL,
  prompt text NOT NULL, note text NOT NULL, strength text NOT NULL, retake text NOT NULL,
  UNIQUE(map_id, number));
CREATE TABLE options(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id integer NOT NULL REFERENCES questions(id), letter text NOT NULL,
  text text NOT NULL, points integer NOT NULL CHECK(points BETWEEN 0 AND 5), why text NOT NULL,
  UNIQUE(question_id, letter));
CREATE TABLE attempts(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(id), map_id integer NOT NULL REFERENCES maps(id),
  status text NOT NULL DEFAULT 'in_progress' CHECK(status IN ('in_progress','completed','voided')),
  total_points integer NOT NULL DEFAULT 0, started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz, voided_at timestamptz);
CREATE UNIQUE INDEX ux_attempt_active ON attempts(student_id, map_id) WHERE status <> 'voided';
CREATE TABLE answers(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id integer NOT NULL REFERENCES attempts(id), question_id integer NOT NULL REFERENCES questions(id),
  option_id integer NOT NULL REFERENCES options(id), points integer NOT NULL, display_pos integer NOT NULL,
  answered_at timestamptz NOT NULL DEFAULT now(), UNIQUE(attempt_id, question_id));
CREATE INDEX ix_answers_question ON answers(question_id);
CREATE TABLE admin_log(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer, action text NOT NULL, student_id integer, detail text,
  created_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX ix_admin_log_student ON admin_log(student_id);
CREATE TABLE sessions(token_hash text PRIMARY KEY, role text NOT NULL, user_id integer NOT NULL, expires_at bigint NOT NULL);
CREATE TABLE login_attempts(key text PRIMARY KEY, fails integer NOT NULL DEFAULT 0, window_start bigint NOT NULL, locked_until bigint NOT NULL DEFAULT 0);
CREATE TABLE settings(key text PRIMARY KEY, value text NOT NULL);
