-- Reversão (se um dia for necessário): DROP TABLE integrity_audit, integrity_events; e remover as colunas "integrity_*"
-- e "served_*" de attempts. As pontuações originais não são tocadas por esta migração.

-- Ocorrências de integridade. O aluno NÃO tem rota de leitura, edição ou exclusão desta tabela.
-- Ao excluir o aluno, as ocorrências dele são apagadas junto (LGPD).
CREATE TABLE integrity_events(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  session_ref text,                         -- prefixo do hash da sessão (não é o token): liga o evento à sessão sem expô-la
  assessment_id integer REFERENCES assessments(id) ON DELETE SET NULL,
  attempt_id integer REFERENCES attempts(id) ON DELETE SET NULL,
  event_type text NOT NULL,                 -- ver INTEGRITY_EVENTS em lib/integrity.ts
  severity smallint NOT NULL CHECK (severity BETWEEN 1 AND 3),
  certainty text NOT NULL CHECK (certainty IN ('detected','indicator')), -- detected = observado nos componentes do jogo; indicator = sinal que exige análise
  source text NOT NULL CHECK (source IN ('client','server')),
  evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
  device text,                              -- classe coarse: "celular · Android · Chrome" (sem identificadores únicos)
  detected_at timestamptz NOT NULL DEFAULT now(),
  penalty text NOT NULL DEFAULT 'none' CHECK (penalty IN ('none','warning','suspension','block')),
  points_deducted integer NOT NULL DEFAULT 0 CHECK (points_deducted >= 0),
  penalty_cancelled_at timestamptz,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','confirmed','justified')),
  reviewed_by integer REFERENCES teachers(id) ON DELETE SET NULL,
  reviewed_at timestamptz);
CREATE INDEX ix_integrity_student ON integrity_events(student_id, detected_at DESC);
CREATE INDEX ix_integrity_attempt ON integrity_events(attempt_id);
CREATE INDEX ix_integrity_detected ON integrity_events(detected_at);

-- Trilha de auditoria: toda decisão do professor (e mudança de regras) fica registrada e não pode ser editada pela API.
CREATE TABLE integrity_audit(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint REFERENCES integrity_events(id) ON DELETE SET NULL,
  attempt_id integer,
  teacher_id integer REFERENCES teachers(id) ON DELETE SET NULL,
  action text NOT NULL,
  detail text,
  created_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX ix_integrity_audit_event ON integrity_audit(event_id, created_at);

-- Estado de integridade da tentativa (partida) e controle de tempo plausível das respostas.
ALTER TABLE attempts
  ADD COLUMN integrity_status text NOT NULL DEFAULT 'ok' CHECK (integrity_status IN ('ok','suspended','blocked')),
  ADD COLUMN integrity_until timestamptz,          -- fim da suspensão temporária
  ADD COLUMN integrity_event_id bigint,            -- ocorrência que causou o estado atual
  ADD COLUMN integrity_released_at timestamptz,    -- última liberação (zera a contagem de reincidência)
  ADD COLUMN served_question_id integer,           -- pergunta entregue ao aluno por último
  ADD COLUMN served_at timestamptz;                -- quando foi entregue pela primeira vez (base do tempo mínimo plausível)
