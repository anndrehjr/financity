ALTER TABLE maps ALTER COLUMN subject_id SET NOT NULL;
-- a ordem e a situação passam a ser da avaliação (por série); as colunas antigas ficam como legado.
ALTER TABLE maps ALTER COLUMN sort DROP NOT NULL;
ALTER TABLE maps DROP CONSTRAINT maps_sort_key;

CREATE TABLE assessments(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  map_id integer NOT NULL REFERENCES maps(id),
  grade smallint NOT NULL CHECK (grade BETWEEN 1 AND 12),
  sort integer NOT NULL,
  status text NOT NULL DEFAULT 'developing' CHECK (status IN ('available','developing')),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(grade, sort), UNIQUE(grade, map_id));
INSERT INTO assessments(id, map_id, grade, sort, status)
