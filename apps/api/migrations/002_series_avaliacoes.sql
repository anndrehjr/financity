  SELECT id, id, 8, sort, status FROM maps;
SELECT setval(pg_get_serial_sequence('assessments','id'), GREATEST((SELECT COALESCE(MAX(id),0) FROM assessments),1), (SELECT COUNT(*)>0 FROM assessments));

ALTER TABLE attempts ADD COLUMN assessment_id integer REFERENCES assessments(id);
