-- 002: séries, matérias, avaliações por série e vínculo professor↔turma.
-- Aditiva: nenhuma coluna ou linha existente é apagada. Os dados atuais (sistema do 8º ano) viram avaliações do 8º ano
-- mantendo os mesmos IDs (avaliação N = mapa N), então tentativas e respostas continuam válidas.

ALTER TABLE classes ADD COLUMN grade smallint CHECK (grade BETWEEN 1 AND 12);
-- série deduzida do nome da turma ("8 ano", "8º A", "7º B"...). Turmas sem número ficam NULL (sem atividades) até o professor corrigir.
UPDATE classes SET grade = (substring(name from '(\d{1,2})'))::smallint
 WHERE grade IS NULL AND name ~ '\d' AND (substring(name from '(\d{1,2})'))::int BETWEEN 1 AND 12;

CREATE TABLE subjects(
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE, name text NOT NULL);
INSERT INTO subjects(slug, name) VALUES ('educacao-financeira', 'Educação Financeira');

