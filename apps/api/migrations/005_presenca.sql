-- 005: presença dos alunos (hora de entrada, último sinal, saída). ADITIVA: só cria uma tabela nova.
-- Nada do que já existe (alunos, senhas, tentativas, respostas, sessões) é alterado.
-- Ao excluir um aluno, o histórico de presença dele é apagado junto (ON DELETE CASCADE).
CREATE TABLE presence(
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  token_hash text NOT NULL,
  started_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  ended_at timestamptz,
  end_reason text);
CREATE INDEX ix_presence_student ON presence(student_id, started_at DESC);
CREATE INDEX ix_presence_token ON presence(token_hash) WHERE ended_at IS NULL;
